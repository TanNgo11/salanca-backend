describe('admin translation coverage', () => {
  it('leaves no English message id inside a covered area', () => {
    const overrides = buildAdminTranslationOverrides();
    const leftovers = collectMissingAdminMessageIds(overrides).filter((entry) =>
      COVERED_MESSAGE_PREFIXES.some((prefix) => entry.id.startsWith(prefix)),
    );

    expect(leftovers.map((entry) => entry.id)).toEqual([]);
  });
});
