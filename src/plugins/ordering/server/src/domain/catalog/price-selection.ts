import { amountFromDb } from '../money';
import { minutesOf, toLocalParts } from '../scheduling/zoned-time';

/**
 * Pure `catalog-price` selection (contracts §20.1, O14): pick the most specific price
 * row for the request context — a Medusa-style "rules must all match, more rule keys win" —
 * then apply at most one matching `adjust` price list. No Strapi imports; callers pass raw rows.
 *
 * Rule vocabulary: `locationRef`, `channel`, `customerGroup`, `weekdays`, `timeRanges`, plus the
 * row's `validFrom`/`validTo` window and `minQuantity`. Weekdays and time ranges use the branch
 * timezone. A customer in several groups matches every group row; equal specificity then keeps
 * the lower amount, so the customer pays the best of their groups.
 */

export const PRICE_CHANNELS = ['pickup', 'delivery', 'dine-in', 'staff'] as const;
export type PriceChannel = (typeof PRICE_CHANNELS)[number];

export const PRICE_WEEKDAYS = ['mon', 'tue', 'wed', 'thu', 'fri', 'sat', 'sun'] as const;
export type PriceWeekday = (typeof PRICE_WEEKDAYS)[number];

export type PriceTimeRange = { start: string; end: string };

export type CatalogPriceRules = {
  locationRef?: string | null;
  channel?: string | null;
  customerGroup?: string | null;
  /**
   * List-level OR constraints. Empty or omitted means "no constraint". A catalog-price row keeps
   * using the singular keys; an adjust list may name several channels, branches or groups.
   */
  channels?: string[] | null;
  locationRefs?: string[] | null;
  customerGroups?: string[] | null;
  /** Empty or omitted = every day. Values are `mon`…`sun`. */
  weekdays?: string[] | null;
  /** Empty or omitted = all day. `end` <= `start` wraps past midnight; `end` is exclusive. */
  timeRanges?: PriceTimeRange[] | null;
};

export type CatalogPriceRow = {
  amount: number | string | bigint;
  compareAtAmount?: number | string | bigint | null;
  currency: string;
  minQuantity?: number | null;
  rules?: CatalogPriceRules | null;
  priority?: number | null;
  validFrom?: string | Date | null;
  validTo?: string | Date | null;
  /**
   * Owning price list, when the row was generated by an override list. Callers drop rows whose
   * list is inactive before selection; the pure function ignores this field.
   */
  priceList?: { active?: boolean | null } | null;
};

export type PriceContext = {
  at?: Date;
  locationRef?: string | null;
  channel?: string | null;
  /** Single group. Combined with `customerGroups` when the customer belongs to several. */
  customerGroup?: string | null;
  customerGroups?: readonly string[] | null;
  quantity?: number;
  /** IANA zone for `weekdays` and `timeRanges`. A row that uses them does not match without it. */
  timezone?: string | null;
};

export type SelectedPrice = {
  amount: number;
  compareAtAmount?: number;
  currency: string;
  /** Rule keys this row matched — used by diagnostics and tests. */
  matchedRules: string[];
};

export type AdjustTarget = {
  kind: 'all' | 'categories' | 'products';
  refs?: string[] | null;
};

export type AdjustList = {
  id: string | number;
  name?: string | null;
  priority?: number | null;
  active?: boolean | null;
  rules?: CatalogPriceRules | null;
  validFrom?: string | Date | null;
  validTo?: string | Date | null;
  adjust: {
    type: 'percent' | 'amount';
    value: number;
    target: AdjustTarget;
  };
};

export type VariantPriceContext = {
  variantRef?: string | null;
  productRef?: string | null;
  categoryRefs?: readonly string[] | null;
};

export type AdjustedPrice = SelectedPrice & {
  priceListId?: string | number;
  priceListName?: string;
};

const SCALAR_RULES = ['locationRef', 'channel', 'customerGroup'] as const;

const toTime = (value: string | Date | null | undefined): number | null => {
  if (value === null || value === undefined) return null;
  const time = value instanceof Date ? value.getTime() : Date.parse(value);
  return Number.isNaN(time) ? null : time;
};

/** `web-checkout` used to mean "no channel"; `phone-staff` is the staff channel. */
const canonicalChannel = (channel: string): string | null => {
  if (channel === 'web-checkout') return null;
  if (channel === 'phone-staff') return 'staff';
  return channel;
};

const contextGroups = (ctx: PriceContext): Set<string> => {
  const groups = new Set<string>();
  if (ctx.customerGroup) groups.add(ctx.customerGroup);
  for (const group of ctx.customerGroups ?? []) {
    if (group) groups.add(group);
  }
  return groups;
};

const inTimeRange = (minute: number, range: PriceTimeRange): boolean => {
  const start = minutesOf(range.start);
  const end = minutesOf(range.end);
  if (start === end) return false;
  if (end > start) return minute >= start && minute < end;
  return minute >= start || minute < end;
};

const windowCovers = (
  validFrom: string | Date | null | undefined,
  validTo: string | Date | null | undefined,
  now: number,
): boolean => {
  const from = toTime(validFrom);
  const to = toTime(validTo);
  if (from !== null && now < from) return false;
  if (to !== null && now > to) return false;
  return true;
};

/**
 * Matched rule keys, or null when a present rule misses the context. Empty weekdays and
 * time ranges are not rules. A legacy `web-checkout` channel is not a rule either.
 */
const matchScore = (
  rules: CatalogPriceRules | null | undefined,
  ctx: PriceContext,
): { score: number; matched: string[] } | null => {
  const source = rules ?? {};
  const matched: string[] = [];
  for (const key of SCALAR_RULES) {
    const raw = source[key];
    if (raw === undefined || raw === null || raw === '') continue;
    if (key === 'channel') {
      const wanted = canonicalChannel(raw);
      if (wanted === null) continue;
      if (!ctx.channel || ctx.channel !== wanted) return null;
      matched.push(key);
      continue;
    }
    if (key === 'customerGroup') {
      if (!contextGroups(ctx).has(raw)) return null;
      matched.push(key);
      continue;
    }
    const got = ctx.locationRef;
    if (got === undefined || got === null || got !== raw) return null;
    matched.push(key);
  }

  const weekdays = (source.weekdays ?? []).filter((day) => day !== '');
  const ranges = (source.timeRanges ?? []).filter((range) => range?.start && range?.end);
  if (weekdays.length > 0 || ranges.length > 0) {
    if (!ctx.timezone) return null;
    const local = toLocalParts(ctx.at ?? new Date(), ctx.timezone);
    if (weekdays.length > 0) {
      const weekday = PRICE_WEEKDAYS[local.weekday];
      if (!weekday || !weekdays.includes(weekday)) return null;
      matched.push('weekdays');
    }
    if (ranges.length > 0) {
      const minute = minutesOf(local.time);
      if (!ranges.some((range) => inTimeRange(minute, range))) return null;
      matched.push('timeRanges');
    }
  }
  return { score: matched.length, matched };
};

/**
 * Whether an adjust list's rules hold. Singular keys and the list-level arrays are OR within
 * one dimension and AND across dimensions. Weekdays and time ranges delegate to the row matcher.
 */
export const priceRulesMatch = (
  rules: CatalogPriceRules | null | undefined,
  ctx: PriceContext,
): boolean => {
  const source = rules ?? {};
  const channels = [...(source.channels ?? [])];
  if (source.channel) {
    const canonical = canonicalChannel(source.channel);
    if (canonical) channels.push(canonical);
  }
  if (channels.length > 0 && (!ctx.channel || !channels.includes(ctx.channel))) return false;

  const locations = [...(source.locationRefs ?? [])];
  if (source.locationRef) locations.push(source.locationRef);
  if (locations.length > 0 && (!ctx.locationRef || !locations.includes(ctx.locationRef))) return false;

  const groups = [...(source.customerGroups ?? [])];
  if (source.customerGroup) groups.push(source.customerGroup);
  if (groups.length > 0 && !groups.some((group) => contextGroups(ctx).has(group))) return false;

  return matchScore({ weekdays: source.weekdays, timeRanges: source.timeRanges }, ctx) !== null;
};

const targetMatches = (target: AdjustTarget, variant: VariantPriceContext): boolean => {
  if (target.kind === 'all') return true;
  const refs = new Set(target.refs ?? []);
  if (refs.size === 0) return false;
  if (target.kind === 'products') {
    return (
      (variant.productRef !== undefined && variant.productRef !== null && refs.has(variant.productRef)) ||
      (variant.variantRef !== undefined && variant.variantRef !== null && refs.has(variant.variantRef))
    );
  }
  return (variant.categoryRefs ?? []).some((ref) => refs.has(ref));
};

/** Discount in đồng, never negative and never above `base`. Percent rounds down. */
const discountOf = (base: number, adjust: AdjustList['adjust']): number => {
  if (!Number.isFinite(adjust.value) || adjust.value <= 0 || base <= 0) return 0;
  if (adjust.type === 'percent') {
    return Math.min(base, Math.floor((base * adjust.value) / 100));
  }
  return Math.min(base, Math.floor(adjust.value));
};

/**
 * Price channel for an order. A staff draft is always `staff`. Pickup, delivery and dine-in
 * pass through. Appointment (and anything else) has no channel, so only channel-free rows match.
 */
export function priceChannelOf(input: {
  originKind?: string | null;
  receiveKind?: string | null;
}): PriceChannel | undefined {
  if (input.originKind === 'staff-draft') return 'staff';
  if (
    input.receiveKind === 'pickup' ||
    input.receiveKind === 'delivery' ||
    input.receiveKind === 'dine-in'
  ) {
    return input.receiveKind;
  }
  return undefined;
}

/**
 * Returns the winning row or null. Ordering: rule specificity (more matched keys) → explicit
 * `priority` → `minQuantity` (a higher threshold is more specific) → lowest amount, which
 * keeps ties deterministic and gives a multi-group customer their lowest matching price.
 */
export function selectCatalogPrice(
  rows: CatalogPriceRow[],
  ctx: PriceContext = {},
): SelectedPrice | null {
  const now = (ctx.at ?? new Date()).getTime();
  const quantity = ctx.quantity ?? 1;
  let best: { row: CatalogPriceRow; score: number; matched: string[] } | null = null;
  for (const row of rows) {
    if (row.priceList && row.priceList.active === false) continue;
    if (!windowCovers(row.validFrom, row.validTo, now)) continue;
    if ((row.minQuantity ?? 1) > quantity) continue;
    const match = matchScore(row.rules, ctx);
    if (!match) continue;
    const amount = amountFromDb(row.amount);
    const beat = () => {
      if (!best) return true;
      if (match.score !== best.score) return match.score > best.score;
      if ((row.priority ?? 0) !== (best.row.priority ?? 0)) {
        return (row.priority ?? 0) > (best.row.priority ?? 0);
      }
      if ((row.minQuantity ?? 1) !== (best.row.minQuantity ?? 1)) {
        return (row.minQuantity ?? 1) > (best.row.minQuantity ?? 1);
      }
      return amount < amountFromDb(best.row.amount);
    };
    if (beat()) best = { row, score: match.score, matched: match.matched };
  }
  if (!best) return null;
  const compareAt =
    best.row.compareAtAmount === null || best.row.compareAtAmount === undefined
      ? undefined
      : amountFromDb(best.row.compareAtAmount);
  return {
    amount: amountFromDb(best.row.amount),
    ...(compareAt !== undefined ? { compareAtAmount: compareAt } : {}),
    currency: best.row.currency,
    matchedRules: best.matched,
  };
}

/**
 * Applies the single winning `adjust` list on top of a base price. Lists do not stack: the
 * highest `priority` wins, and the lower resulting price breaks a priority tie. The amount
 * never goes below 0. When the list reduces the price, `compareAtAmount` becomes the base.
 */
export function applyAdjustLists(
  base: SelectedPrice,
  lists: AdjustList[],
  variant: VariantPriceContext = {},
  ctx: PriceContext = {},
): AdjustedPrice {
  const now = (ctx.at ?? new Date()).getTime();
  let winner: { list: AdjustList; amount: number } | null = null;
  for (const list of lists) {
    if (list.active === false) continue;
    if (!windowCovers(list.validFrom, list.validTo, now)) continue;
    if (!priceRulesMatch(list.rules, ctx)) continue;
    if (!targetMatches(list.adjust.target, variant)) continue;
    const amount = Math.max(0, base.amount - discountOf(base.amount, list.adjust));
    const beat = () => {
      if (!winner) return true;
      if ((list.priority ?? 0) !== (winner.list.priority ?? 0)) {
        return (list.priority ?? 0) > (winner.list.priority ?? 0);
      }
      if (amount !== winner.amount) return amount < winner.amount;
      return String(list.id) < String(winner.list.id);
    };
    if (beat()) winner = { list, amount };
  }
  if (!winner || winner.amount === base.amount) return base;
  return {
    amount: winner.amount,
    compareAtAmount: base.amount,
    currency: base.currency,
    matchedRules: base.matchedRules,
    priceListId: winner.list.id,
    ...(winner.list.name ? { priceListName: winner.list.name } : {}),
  };
}

export type PriceCandidate = {
  kind: 'base' | 'list';
  id?: string | number;
  name?: string;
  amount?: number;
  matched: boolean;
  reason: string;
};

/**
 * Why each base row and adjust list did or did not win. The preview screen shows this;
 * money still comes from `selectCatalogPrice` + `applyAdjustLists`.
 */
export function explainPrice(
  rows: CatalogPriceRow[],
  lists: AdjustList[],
  variant: VariantPriceContext,
  ctx: PriceContext = {},
): { amount: number | null; compareAtAmount?: number; winner: PriceCandidate | null; candidates: PriceCandidate[] } {
  const now = (ctx.at ?? new Date()).getTime();
  const quantity = ctx.quantity ?? 1;
  const candidates: PriceCandidate[] = [];
  for (const [index, row] of rows.entries()) {
    if (row.priceList && row.priceList.active === false) {
      candidates.push({ kind: 'base', id: index, matched: false, reason: 'inactive' });
      continue;
    }
    if (!windowCovers(row.validFrom, row.validTo, now)) {
      candidates.push({ kind: 'base', id: index, matched: false, reason: 'window', amount: amountFromDb(row.amount) });
      continue;
    }
    if ((row.minQuantity ?? 1) > quantity) {
      candidates.push({ kind: 'base', id: index, matched: false, reason: 'quantity', amount: amountFromDb(row.amount) });
      continue;
    }
    const match = matchScore(row.rules, ctx);
    candidates.push({
      kind: 'base',
      id: index,
      matched: match !== null,
      reason: match ? 'match' : 'rules',
      amount: amountFromDb(row.amount),
    });
  }
  const base = selectCatalogPrice(rows, ctx);
  if (!base) {
    return { amount: null, winner: null, candidates };
  }
  for (const list of lists) {
    if (list.active === false) {
      candidates.push({ kind: 'list', id: list.id, ...(list.name ? { name: list.name } : {}), matched: false, reason: 'inactive' });
      continue;
    }
    if (!windowCovers(list.validFrom, list.validTo, now)) {
      candidates.push({ kind: 'list', id: list.id, ...(list.name ? { name: list.name } : {}), matched: false, reason: 'window' });
      continue;
    }
    if (!priceRulesMatch(list.rules, ctx)) {
      candidates.push({ kind: 'list', id: list.id, ...(list.name ? { name: list.name } : {}), matched: false, reason: 'rules' });
      continue;
    }
    if (!targetMatches(list.adjust.target, variant)) {
      candidates.push({ kind: 'list', id: list.id, ...(list.name ? { name: list.name } : {}), matched: false, reason: 'target' });
      continue;
    }
    const amount = Math.max(0, base.amount - discountOf(base.amount, list.adjust));
    candidates.push({
      kind: 'list',
      id: list.id,
      ...(list.name ? { name: list.name } : {}),
      matched: true,
      reason: 'match',
      amount,
    });
  }
  const adjusted = applyAdjustLists(base, lists, variant, ctx);
  const winner: PriceCandidate =
    adjusted.priceListId !== undefined
      ? {
          kind: 'list',
          id: adjusted.priceListId,
          ...(adjusted.priceListName ? { name: adjusted.priceListName } : {}),
          matched: true,
          reason: 'winner',
          amount: adjusted.amount,
        }
      : { kind: 'base', matched: true, reason: 'winner', amount: adjusted.amount };
  return {
    amount: adjusted.amount,
    ...(adjusted.compareAtAmount !== undefined ? { compareAtAmount: adjusted.compareAtAmount } : {}),
    winner,
    candidates,
  };
}
